// Builds extension/src/azure/drs-data.js from Microsoft's "Front Door WAF DRS rule groups and rules"
// documentation (saved as markdown in vendor/azure-afd-drs.md, e.g. via a web-to-markdown fetch of
// https://learn.microsoft.com/en-us/azure/web-application-firewall/afds/waf-front-door-drs).
//   node scripts/gen-azure-drs.mjs [vendor/azure-afd-drs.md]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2] || path.join(ROOT, 'vendor', 'azure-afd-drs.md');
const lines = readFileSync(src, 'utf8').split(/\r?\n/);

// Heading text in the docs -> ruleGroupName used in WAF policy JSON.
const GROUPS = {
  'general': 'General',
  'method enforcement': 'METHOD-ENFORCEMENT',
  'protocol enforcement': 'PROTOCOL-ENFORCEMENT',
  'protocol attack': 'PROTOCOL-ATTACK',
  'lfi: local file inclusion': 'LFI',
  'rfi: remote file inclusion': 'RFI',
  'rce: remote command execution': 'RCE',
  'php attacks': 'PHP',
  'node.js attacks': 'NODEJS',
  'xss: cross-site scripting': 'XSS',
  'sqli: sql injection': 'SQLI',
  'session fixation': 'FIX',
  'java attacks': 'JAVA',
  'ms-threatintel-webshells': 'MS-ThreatIntel-WebShells',
  'ms-threatintel-appsec': 'MS-ThreatIntel-AppSec',
  'ms-threatintel-sqli': 'MS-ThreatIntel-SQLI',
  'ms-threatintel-cves': 'MS-ThreatIntel-CVEs',
  'ms-threatintel-xss': 'MS-ThreatIntel-XSS',
};

const sets = {}; // version -> { rules: {id: {...}}, disabled: Set }
let version = null;
let group = null;
let inDisabledTable = null;
for (let i = 0; i < lines.length; i++) {
  const l = lines[i];
  let m;
  // Overview "disabled by default" tables (before the per-version tabs).
  if ((m = /disabled by default for DRS (\d\.\d)/i.exec(l))) {
    inDisabledTable = m[1];
    (sets[inDisabledTable] ||= { rules: {}, disabled: new Set() });
    continue;
  }
  if ((m = /^# \[DRS (\d\.\d)\]/.exec(l))) {
    version = m[1];
    inDisabledTable = null;
    sets[version] ||= { rules: {}, disabled: new Set() };
    continue;
  }
  if (/^# \[/.test(l) && !/^# \[DRS/.test(l)) {
    version = null; // bot manager tabs etc.
    continue;
  }
  if ((m = /^### (.+)$/.exec(l))) {
    group = GROUPS[m[1].trim().toLowerCase()] || null;
    if (!version) inDisabledTable = inDisabledTable; // keep
    continue;
  }
  if (/^##? /.test(l) && !/^## \d\.\d rule sets/i.test(l)) inDisabledTable = null;
  const row = /^\|\s*(\d{6,8})\s*\|(.*)\|\s*$/.exec(l);
  if (!row) continue;
  const id = Number(row[1]);
  const cells = row[2].split('|').map((c) => c.trim());
  if (inDisabledTable && !version) {
    sets[inDisabledTable].disabled.add(id);
    continue;
  }
  if (!version || !group) continue;
  let severity = null, score = null, pl = null, description;
  if (cells.length >= 3 && /-\s*\d/.test(cells[0])) {
    const sm = /^(\w+)\s*-\s*(\d+)/.exec(cells[0]);
    severity = sm ? sm[1].toUpperCase() : null;
    score = sm ? Number(sm[2]) : null;
    pl = Number(cells[1]) || null;
    description = cells.slice(2).join(' | ');
  } else {
    description = cells.join(' | ');
  }
  description = description.replace(/\[([^\]]+)\]\([^)]*\)/g, '$1');
  const replaced = /replaced by (?:MSTIC )?rule #?(\d+)/i.exec(description);
  sets[version].rules[id] = { group, pl, severity, score, description, replacedBy: replaced ? Number(replaced[1]) : null };
}

// Default state: DRS 2.2 disables PL2 rules and replaced OWASP rules; earlier versions list theirs.
const out = {};
for (const [v, s] of Object.entries(sets)) {
  if (!Object.keys(s.rules).length) continue;
  const disabled = new Set(s.disabled);
  for (const [id, r] of Object.entries(s.rules)) {
    if (v === '2.2' && (r.pl === 2 || r.replacedBy)) disabled.add(Number(id));
  }
  out[v] = { rules: s.rules, defaultDisabled: [...disabled].sort((a, b) => a - b) };
}

const summary = Object.entries(out).map(([v, s]) => `${v}: ${Object.keys(s.rules).length} rules, ${s.defaultDisabled.length} disabled by default`);
mkdirSync(path.join(ROOT, 'extension', 'src', 'azure'), { recursive: true });
writeFileSync(
  path.join(ROOT, 'extension', 'src', 'azure', 'drs-data.js'),
  `// Generated by scripts/gen-azure-drs.mjs from Microsoft Learn "Front Door WAF DRS rule groups and rules".
// Do not edit by hand. ${summary.join('; ')}
// Base CRS: DRS 2.2 -> CRS 3.3.4, DRS 2.1/2.0 -> CRS 3.3.x (+ Microsoft Threat Intelligence rules 99xxxxxx).
export const DRS = ${JSON.stringify(out)};
`
);
console.log(summary.join('\n'));
