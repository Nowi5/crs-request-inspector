// Generates extension/src/engine/unicode-map.js from ModSecurity's unicode.mapping
// (code page 20127, as configured by `SecUnicodeMapFile unicode.mapping 20127` in
// modsecurity.conf-recommended). Used by t:urlDecodeUni for %uXXXX "best fit" mapping.
//   curl -s https://raw.githubusercontent.com/owasp-modsecurity/ModSecurity/v2/master/unicode.mapping -o vendor/unicode.mapping
import { readFileSync, writeFileSync } from 'node:fs';
const text = readFileSync('vendor/unicode.mapping', 'utf8');
const lines = text.split(/\r?\n/);
const start = lines.findIndex((l) => /^20127\b/.test(l));
const pairs = [];
for (let i = start + 1; i < lines.length && !/^\d+ \(/.test(lines[i]); i++) {
  for (const m of lines[i].matchAll(/([0-9a-f]{4}):([0-9a-f]{2})/gi)) pairs.push([parseInt(m[1], 16), parseInt(m[2], 16)]);
}
const out = `// Generated by scripts/gen-unicode-map.mjs from ModSecurity's unicode.mapping (code page 20127).
// Do not edit by hand. ${pairs.length} entries: code point -> best-fit ASCII byte.
const PAIRS = '${pairs.map(([c, b]) => c.toString(16).padStart(4, '0') + b.toString(16).padStart(2, '0')).join('')}';
export const UNICODE_MAP = new Map();
for (let i = 0; i < PAIRS.length; i += 6) UNICODE_MAP.set(parseInt(PAIRS.slice(i, i + 4), 16), parseInt(PAIRS.slice(i + 4, i + 6), 16));
`;
writeFileSync('extension/src/engine/unicode-map.js', out);
console.log('pairs', pairs.length);
