// Builds a RuleSet from the bundled CRS files plus a generated crs-setup and
// optional user rules. Works in the browser (fetch) and in Node (custom reader).

import { RuleSet } from './engine.js';
import { bytesToBinary, utf8ToBinary } from './bytes.js';

export const DEFAULT_SETTINGS = {
  version: null, // CRS version (index.default when null)
  blockingParanoiaLevel: 1,
  detectionParanoiaLevel: 4,
  inboundThreshold: 5,
  outboundThreshold: 4,
  earlyBlocking: false,
  includeModsecRecommended: true,
  evaluateResponses: true,
  continueAfterBlock: true,
  remoteAddr: '203.0.113.10',
  protocolOverride: '', // '', 'HTTP/1.1', 'HTTP/2.0'
  customRulesBefore: '',
  customRulesAfter: '',
  wafProfile: 'crs', // 'crs' (ModSecurity/Coraza + CRS) | 'azure' (imported Azure WAF policy)
  azurePolicy: '', // Azure WAF policy JSON (portal JSON view / az CLI / ARM export)
  clientCountry: '', // ISO country code used for Azure GeoMatch custom rules
  clientIp: '', // client IP used for Azure IPMatch custom rules ('' = unknown)
};

/** "v4.30.0" -> 4300, "v3.3.10" -> 3310 */
export function setupVersionNumber(version) {
  return parseInt(String(version).replace(/^v/, '').replace(/[^0-9]/g, ''), 10) || 0;
}

export function isCrs4(version) {
  return /^v?4\./.test(String(version)) || /^v?[5-9]\./.test(String(version));
}

/** Generated equivalent of crs-setup.conf for the selected settings. */
export function crsSetupText(version, s) {
  const v4 = isCrs4(version);
  const lines = [
    '# Generated by CRS Request Inspector (equivalent of crs-setup.conf)',
    'SecDefaultAction "phase:1,log,auditlog,pass"',
    'SecDefaultAction "phase:2,log,auditlog,pass"',
    'SecDefaultAction "phase:3,log,auditlog,pass"',
    'SecDefaultAction "phase:4,log,auditlog,pass"',
    'SecDefaultAction "phase:5,log,auditlog,pass"',
  ];
  const bpl = Math.min(4, Math.max(1, +s.blockingParanoiaLevel || 1));
  const dpl = Math.min(4, Math.max(bpl, +s.detectionParanoiaLevel || bpl));
  if (v4) {
    lines.push(`SecAction "id:900000,phase:1,pass,t:none,nolog,tag:'OWASP_CRS',setvar:tx.blocking_paranoia_level=${bpl}"`);
    lines.push(`SecAction "id:900001,phase:1,pass,t:none,nolog,tag:'OWASP_CRS',setvar:tx.detection_paranoia_level=${dpl}"`);
    if (s.earlyBlocking) lines.push(`SecAction "id:900120,phase:1,pass,t:none,nolog,tag:'OWASP_CRS',setvar:tx.early_blocking=1"`);
  } else {
    lines.push(`SecAction "id:900000,phase:1,pass,t:none,nolog,setvar:tx.paranoia_level=${bpl}"`);
    lines.push(`SecAction "id:900001,phase:1,pass,t:none,nolog,setvar:tx.executing_paranoia_level=${dpl}"`);
  }
  lines.push(
    `SecAction "id:900110,phase:1,pass,t:none,nolog,${v4 ? "tag:'OWASP_CRS'," : ''}setvar:tx.inbound_anomaly_score_threshold=${+s.inboundThreshold || 5},setvar:tx.outbound_anomaly_score_threshold=${+s.outboundThreshold || 4}"`
  );
  lines.push(`SecAction "id:900990,phase:1,pass,t:none,nolog,${v4 ? "tag:'OWASP_CRS'," : ''}setvar:tx.crs_setup_version=${setupVersionNumber(version)}"`);
  return lines.join('\n') + '\n';
}

/**
 * @param {object} p
 * @param {(path: string) => Promise<string>} p.readText   returns file content as byte string (latin1)
 * @param {object} p.index      parsed rulesets/index.json
 * @param {object} p.settings
 */
export async function loadRuleSet({ readText, index, settings }) {
  const s = { ...DEFAULT_SETTINGS, ...settings };
  const entry = index.rulesets.find((r) => r.version === (s.version || index.default)) || index.rulesets[0];
  if (!entry) throw new Error('No CRS rule set bundled. Run `node scripts/fetch-crs.mjs`.');
  const dataFiles = new Map();
  await Promise.all(
    entry.dataFiles.map(async (f) => {
      try {
        dataFiles.set(f, await readText(`${entry.path}/rules/${f}`));
      } catch {
        /* reported by the operator when used */
      }
    })
  );
  const rs = new RuleSet({ dataFiles, meta: { version: entry.version, missing: entry.missing || [] } });

  if (s.includeModsecRecommended) {
    try {
      const rec = await readText('modsecurity/modsecurity.conf-recommended');
      rs.addFile('modsecurity.conf-recommended', rec, {
        origin: 'modsecurity',
        ignoreDirectives: ['SecRuleEngine', 'SecAuditEngine', 'SecAuditLog', 'SecAuditLogParts', 'SecAuditLogType', 'SecTmpDir', 'SecDataDir', 'SecUnicodeMapFile', 'SecStatusEngine'],
      });
    } catch (e) {
      rs.errors.push({ file: 'modsecurity.conf-recommended', line: 0, message: `not loaded: ${e.message}` });
    }
  }
  rs.addFile('crs-setup.conf (generated)', crsSetupText(entry.version, s), { origin: 'setup' });
  if (s.customRulesBefore && s.customRulesBefore.trim()) rs.addFile('custom-before-crs.conf', utf8ToBinary(s.customRulesBefore), { origin: 'custom' });
  const files = [...entry.files].filter((f) => f.endsWith('.conf')).sort();
  const texts = await Promise.all(files.map((f) => readText(`${entry.path}/rules/${f}`)));
  files.forEach((f, i) => rs.addFile(f, texts[i], { origin: 'crs' }));
  if (s.customRulesAfter && s.customRulesAfter.trim()) rs.addFile('custom-after-crs.conf', utf8ToBinary(s.customRulesAfter), { origin: 'custom' });
  rs.finalize();
  rs.meta.settings = s;
  rs.meta.entry = entry;
  return rs;
}

/** Reader for extension pages / workers: base URL of the rulesets folder. */
export function fetchReader(baseUrl) {
  return async (p) => {
    const res = await fetch(new URL(p, baseUrl));
    if (!res.ok) throw new Error(`${p}: HTTP ${res.status}`);
    return bytesToBinary(await res.arrayBuffer());
  };
}
